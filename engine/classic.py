# 运势档位对主题的加权：低分偏守，高分偏进
LOW_TOTAL = ["守静", "坚韧", "修身"]
HIGH_TOTAL = ["进取", "践行", "决断"]


def _themes_for(wx: str, total: float, health_score: Optional[float] = None) -> List[str]:
    """按五行、运势档位、健康分排出今日候选主题（前面的优先）。"""
    base = list(WX_THEMES.get(wx, ["修身", "守静", "践行"]))
    pref: List[str] = []
    # 健康分偏低时，养生提到最前（六十四卦不给健康打分，这一路只有它能进）
    if health_score is not None and health_score < 50:
        pref.append("养生")
    if total < 45:
        pref += LOW_TOTAL
    elif total >= 75:
        pref += HIGH_TOTAL
    return [t for t in pref if t in CLASSICS] + [t for t in base if t not in pref]


def daily_classic(ctx: Dict, zhouyi_pan: Optional[Dict] = None,
                  health_score: Optional[float] = None) -> Dict:
    """生成今日一句经典。

    ctx 需含 target / lr_day / total；zhouyi_pan 用于把卦名写进「为何选此句」。
    整个过程不联网、不随机，同一天必得同一句。
    """
    target: datetime = ctx["target"]
    day_gz = (ctx.get("lr_day") or {}).get("gz", "") or ""
    gan = day_gz[0] if day_gz else ""
    wx = gan_wuxing(gan) if gan else ""
    total = float(ctx.get("total", 50) or 50)

    ordinal = target.toordinal()
    themes = _themes_for(wx, total, health_score)
    theme = themes[ordinal % len(themes)]

    pool = CLASSICS[theme]
    book, chapter, text, zh = pool[ordinal % len(pool)]
    acts = ACTIONS[theme]
    note = acts[ordinal % len(acts)]

    gua_name = (zhouyi_pan or {}).get("name", "")
    gua_sym = (zhouyi_pan or {}).get("symbol", "") or (zhouyi_pan or {}).get("gua_sym", "")
    if gua_name:
        why = (f"今日{day_gz}日，日干{gan}属{wx}；值{gua_name}，"
               f"运势{total:.0f}分 —— 配「{theme}」类")
    else:
        why = f"今日{day_gz}日，日干{gan}属{wx}，运势{total:.0f}分 —— 配「{theme}」类"

    return {
        "theme": theme,
        "book": book,
        "chapter": chapter,
        "text": text,
        "zh": zh,
        "note": note,
        "why": why,
        "day_gz": day_gz,
        "wuxing": wx,
        "gua": gua_name,
        "gua_sym": gua_sym,
        "pool_size": len(pool),
    }


def render_classic_text(c: Dict) -> str:
    """纯文本版（降级正文用）。"""
    if not c:
        return ""
    return (f"【每日一句经典 · {c['theme']}】\n"
            f"  {c['text']}\n"
            f"  —— {c['book']}·{c['chapter']}\n"
            f"  【白话】{c['zh']}\n"
            f"  【今日提点】{c['note']}\n"
            f"  【为何选此句】{c['why']}")


