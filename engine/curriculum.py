# ---------------------------------------------------------------- 易经轨道生成

def _build_yijing() -> List[_L]:
    """六十四卦课时：内容直接取自 gua64_data，不另写一遍，避免两处走样。"""
    from .gua64_data import GUA64_DATA
    from .yijing import GUA64

    items = sorted(GUA64_DATA.items(), key=lambda kv: kv[1].get("xu", 0))
    out: List[_L] = []
    for (up, low), v in items:
        xu = v.get("xu", 0)
        name = GUA64.get((up, low), "")
        ci = str(v.get("ci", "")).strip()
        bai = str(v.get("ci_bai", "")).strip()
        xiang = str(v.get("xiang", "")).strip()
        yi = str(v.get("yi", "")).strip()
        yong = str(v.get("yong", "")).strip()

        pts = []
        if ci:
            pts.append(f"卦辞：{ci}")
        if bai:
            pts.append(f"卦辞白话：{bai}")
        if xiang:
            pts.append(f"大象传：{xiang}")
        if yi:
            pts.append(f"义理：{yi}")

        out.append(_les(
            f"第{xu}卦 {name}",
            pts or [f"第{xu}卦精读"],
            f"今日之用：{yong}" if yong else f"读第{xu}卦卦辞与大象传，各抄一遍。",
            q=ci,
            s=f"周易 第{xu}卦 {name} 讲解",
        ))
    return out


def _gen_lessons(kind: str) -> List[_L]:
    if kind == "yijing64":
        return _build_yijing()
    return []


# ---------------------------------------------------------------- 取课

def all_tracks() -> List[Dict[str, object]]:
    """展开后的轨道列表（含自动生成的课时）。"""
    out = []
    for tr in TRACKS:
        tr = dict(tr)
        if tr.get("gen"):
            tr["lessons"] = _gen_lessons(str(tr["gen"]))
        out.append(tr)
    return out


def total_lessons(tracks: Optional[List[Dict[str, object]]] = None) -> int:
    return sum(len(t.get("lessons") or []) for t in (tracks or all_tracks()))


def lesson_for(date: datetime, tracks: Optional[List[Dict[str, object]]] = None
               ) -> Dict[str, object]:
    """按日期确定性地取一节课。

    以「2026-09-29」为起算日（项目启用日），之后每天推进一节，走完一轮再循环。
    同一天必定同一节，不会因为时区、运行环境而漂移。
    """
    tracks = tracks or all_tracks()
    start = datetime(2026, 9, 29).toordinal()
    step = (date.toordinal() - start) % max(1, total_lessons(tracks))

    acc = 0
    for tr in tracks:
        lessons = tr.get("lessons") or []
        if step < acc + len(lessons):
            i = step - acc
            les = dict(lessons[i])
            title = str(les.get("t", ""))
            kw = str(les.get("s") or f"{tr['name']} {title}")
            links = [{"label": "B站讲解", "url": _bili(kw)}]
            if les.get("w"):
                links.append({"label": "原文", "url": str(les["w"])})
            return {
                "track": tr["name"],
                "kind": tr.get("kind", ""),
                "desc": tr.get("desc", ""),
                "no": i + 1,
                "total": len(lessons),
                "title": title,
                "points": list(les.get("p") or []),
                "quote": str(les.get("q", "")),
                "practice": str(les.get("a", "")),
                "links": links,
                "global_no": step + 1,
                "global_total": total_lessons(tracks),
            }
        acc += len(lessons)
    # 理论上到不了这里（step 已取模）；兜底返回第一节，绝不返回空
    return lesson_for(datetime(2026, 9, 29), tracks)


